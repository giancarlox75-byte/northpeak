// scripts/build-data.js — generates the website's data files:
//   public/data/michigan-map.js  from official U.S. Census Bureau boundaries
// (us-atlas: Census cartographic boundary files) and the Prosperity Regions in src/regions.js
//   public/data/team.js          from the team structure in src/team.js
// Run: npm run build-data
import fs from 'fs';
import { createRequire } from 'module';
import { feature, merge } from 'topojson-client';
import { geoConicConformal, geoPath } from 'd3-geo';
import { REGIONS, COUNTY_TO_REGION } from '../src/regions.js';
import { TEAM_TRACKS, EVENT_TYPES } from '../src/team.js';

const require = createRequire(import.meta.url);
const counties = require('us-atlas/counties-10m.json');
const states = require('us-atlas/states-10m.json');

const geoms = counties.objects.counties.geometries.filter((g) => g.id.startsWith('26'));
// Integrity check: every county in exactly one region
const names = geoms.map((g) => g.properties.name);
const assigned = REGIONS.flatMap((r) => r.counties);
const missing = names.filter((n) => !COUNTY_TO_REGION[n]);
const unknown = assigned.filter((n) => !names.includes(n));
const dupes = assigned.filter((n, i) => assigned.indexOf(n) !== i);
if (names.length !== 83 || missing.length || unknown.length || dupes.length || assigned.length !== 83) {
  console.error({ count: names.length, assigned: assigned.length, missing, unknown, dupes });
  process.exit(1);
}

const W = 600, H = 640;
const stateFeature = feature(states, states.objects.states).features.find((f) => f.id === '26');
const projection = geoConicConformal().parallels([42.1, 47.1]).rotate([86, 0]).fitExtent([[8, 8], [W - 8, H - 8]], stateFeature);
const path = geoPath(projection);
const round = (d) => d.replace(/(\d+\.\d)\d+/g, '$1');
const pt = (p) => p.map((v) => Math.round(v * 10) / 10);

const data = {
  source: 'U.S. Census Bureau cartographic boundary files (us-atlas 3.0.1); regions: State of Michigan Prosperity Regions',
  viewBox: `0 0 ${W} ${H}`,
  state: round(path(stateFeature)),
  counties: geoms.map((g) => {
    const f = feature(counties, g);
    return { fips: g.id, name: g.properties.name, region: COUNTY_TO_REGION[g.properties.name], d: round(path(f)), c: pt(path.centroid(f)) };
  }).sort((a, b) => a.name.localeCompare(b.name)),
  regions: REGIONS.map((r) => {
    const m = merge(counties, geoms.filter((g) => r.counties.includes(g.properties.name)));
    return { id: r.id, num: r.num, name: r.name, cities: r.cities, counties: r.counties, focus: r.focus, issues: r.issues,
      home: r.home || null, connection: r.connection || null, d: round(path(m)), c: pt(path.centroid(m)) };
  }),
};

const out = `/* Generated by scripts/build-data.js. Do not edit by hand. */\nwindow.MI_MAP = ${JSON.stringify(data)};\n`;
fs.writeFileSync(new URL('../public/data/michigan-map.js', import.meta.url), out);
console.log(`✓ michigan-map.js: 83 counties in ${REGIONS.length} regions, ${(out.length / 1024).toFixed(0)} KB`);

const team = `/* Generated by scripts/build-data.js. Do not edit by hand. Edit src/team.js and run npm run build-data. */\nwindow.TR_TEAM = ${JSON.stringify({ tracks: TEAM_TRACKS, eventTypes: EVENT_TYPES })};\n`;
fs.writeFileSync(new URL('../public/data/team.js', import.meta.url), team);
console.log('✓ team.js');
